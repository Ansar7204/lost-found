const UNITS: Record<string, number> = { m: 60_000, h: 3_600_000, d: 86_400_000 };

/** '-2h' -> ISO string 2 hours before `now`. Absolute dates pass through. */
export function resolveTime(value: string, now: Date): string {
  const match = /^-(\d+)([mhd])$/.exec(value);
  if (!match) return new Date(value).toISOString();
  const [, amount, unit] = match;
  return new Date(now.getTime() - Number(amount) * UNITS[unit]).toISOString();
}

