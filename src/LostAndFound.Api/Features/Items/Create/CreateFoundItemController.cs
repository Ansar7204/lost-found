using LostAndFound.Api.Features.Identity;
using LostAndFound.Api.Infrastructure.Persistence;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Identity.Web.Resource;

namespace LostAndFound.Api.Features.Items.Create;

/// <summary>US-02: post a found item.</summary>
[ApiController]
[Route("api/items")]
[Authorize]
[RequiredScope("access_as_user")]
public sealed class CreateFoundItemController(AppDbContext db, TimeProvider clock) : ControllerBase
{
    /// <summary>Small allowance for clocks of phones/laptops that run a bit ahead.</summary>
    private static readonly TimeSpan ClockSkew = TimeSpan.FromMinutes(2);

    [HttpPost]
    [ProducesResponseType<FoundItemDto>(StatusCodes.Status201Created)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest)]
    public async Task<IActionResult> Create(
        CreateFoundItemRequest request,
        CancellationToken cancellationToken)
    {
        if (User.GetUserId() is not { } userId)
        {
            return Unauthorized();
        }

        var name = request.Name.Trim();
        var cabinet = request.Cabinet.Trim();
        var foundAt = request.FoundAt!.Value.ToUniversalTime();

        if (name.Length == 0)
        {
            ModelState.AddModelError(nameof(request.Name), "Say what you found.");
        }
        if (cabinet.Length == 0)
        {
            ModelState.AddModelError(nameof(request.Cabinet), "Where on campus?");
        }
        if (foundAt > clock.GetUtcNow() + ClockSkew)
        {
            ModelState.AddModelError(nameof(request.FoundAt), "The date found can't be in the future.");
        }
        if (!ModelState.IsValid)
        {
            return ValidationProblem(ModelState);
        }

        var item = new FoundItem(
            userId,
            User.GetDisplayName(),
            name,
            request.Description?.Trim() ?? string.Empty,
            request.Category!.Value,
            cabinet,
            request.HeldAt,
            foundAt);

        db.FoundItems.Add(item);
        await db.SaveChangesAsync(cancellationToken); // Number is generated by Postgres here

        return Created($"/api/items/{item.Id}", FoundItemDto.From(item));
    }
}
